// Downloads the site's Google fonts into public/fonts and writes app/fonts.css.
// Run by hand when a font changes: node scripts/fetch-fonts.mjs
// The build never talks to Google; it only reads the files saved here.
import { createHash } from "node:crypto";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Chrome UA so Google answers with woff2 and unicode-range slices.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";

// family: Google name. slug: folder and google/fonts repo dir. query: axis spec. cssVar: the variable the CSS uses.
export const FONTS = [
  { family: "Inter", slug: "inter", query: "Inter:wght@100..900", cssVar: "--font-sans" },
  { family: "Rubik Spray Paint", slug: "rubikspraypaint", query: "Rubik+Spray+Paint", cssVar: "--font-spray" },
  { family: "IBM Plex Mono", slug: "ibmplexmono", query: "IBM+Plex+Mono:wght@400;500", cssVar: "--font-plex" },
  { family: "Noto Sans Malayalam", slug: "notosansmalayalam", query: "Noto+Sans+Malayalam:wght@400;500;600;700", cssVar: "--font-ml" },
  { family: "Noto Sans Devanagari", slug: "notosansdevanagari", query: "Noto+Sans+Devanagari:wght@400;500;600;700", cssVar: "--font-deva" },
  { family: "Noto Sans Tamil", slug: "notosanstamil", query: "Noto+Sans+Tamil:wght@400;500;600;700", cssVar: "--font-ta" },
  { family: "Noto Sans Bengali", slug: "notosansbengali", query: "Noto+Sans+Bengali:wght@400;500;600;700", cssVar: "--font-bn" },
  { family: "Noto Sans SC", slug: "notosanssc", query: "Noto+Sans+SC:wght@400;500;700", cssVar: "--font-zh" },
  { family: "Noto Sans JP", slug: "notosansjp", query: "Noto+Sans+JP:wght@400;500;700", cssVar: "--font-ja" },
  { family: "Noto Sans KR", slug: "notosanskr", query: "Noto+Sans+KR:wght@400;500;700", cssVar: "--font-ko" },
  { family: "Noto Sans Arabic", slug: "notosansarabic", query: "Noto+Sans+Arabic:wght@400;500;600;700", cssVar: "--font-ar" },
];

async function get(url, as) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { headers: { "user-agent": UA } });
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return as === "text" ? await res.text() : Buffer.from(await res.arrayBuffer());
    } catch (err) {
      if (attempt >= 3) throw err;
      await new Promise((r) => setTimeout(r, 1000 * attempt));
    }
  }
}

async function main() {
  const root = join("public", "fonts");
  rmSync(root, { recursive: true, force: true });
  const out = [
    "/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */",
    "/* Self-hosted Google fonts (SIL Open Font License, see public/fonts/<font>/OFL.txt). */",
    "",
  ];
  for (const font of FONTS) {
    const dir = join(root, font.slug);
    mkdirSync(dir, { recursive: true });
    let css = await get(`https://fonts.googleapis.com/css2?family=${font.query}&display=swap`, "text");
    const urls = [...new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+/g) ?? [])];
    if (urls.length === 0) throw new Error(`no font files for ${font.family}`);
    const queue = [...urls];
    const workers = Array.from({ length: 8 }, async () => {
      while (queue.length) {
        const url = queue.shift();
        const name = createHash("sha1").update(url).digest("hex").slice(0, 16) + ".woff2";
        writeFileSync(join(dir, name), await get(url, "buf"));
        css = css.split(url).join(`/fonts/${font.slug}/${name}`);
      }
    });
    await Promise.all(workers);
    const licence = await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${font.slug}/OFL.txt`, "text");
    writeFileSync(join(dir, "OFL.txt"), licence.replace(/\r\n/g, "\n"));
    out.push(`/* ${font.family} */`, css.replace(/\r\n/g, "\n").trim(), "");
    console.log(`${font.family}: ${urls.length} files`);
  }
  // Metric-matched Arial stand-in for Inter while it loads (same numbers next/font used).
  out.push(
    "@font-face {",
    '  font-family: "Inter Fallback";',
    '  src: local("Arial");',
    "  ascent-override: 90.44%;",
    "  descent-override: 22.52%;",
    "  line-gap-override: 0%;",
    "  size-adjust: 107.12%;",
    "}",
    "",
    ":root {",
    ...FONTS.map((f) =>
      f.cssVar === "--font-sans"
        ? `  ${f.cssVar}: "${f.family}", "Inter Fallback";`
        : `  ${f.cssVar}: "${f.family}";`,
    ),
    "}",
    "",
  );
  writeFileSync(join("app", "fonts.css"), out.join("\n"));
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});